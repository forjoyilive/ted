export type Options = {
  [K in keyof typeof flags]?: (typeof flags)[K] extends { type: 'boolean' }
    ? boolean
    : (typeof flags)[K] extends { multiple: true }
      ? string[]
      : string
}

type Scope = 'task' | 'automation' | 'plan' | 'chat'
interface CommandDefinition<H extends string = string> {
  name: string
  handler: H
  options: ParseArgsOptionsConfig
  min: number
  max: number | null
  help: string
  callers: string
  requires?: readonly (keyof Options)[]
  excludes?: readonly (keyof Options)[]
  scope?: Scope
  argumentOrOption?: keyof Options
}

function options(...names: (keyof Options)[]): ParseArgsOptionsConfig {
  const all = names.includes('agent') ? [...names, 'provider' as const] : names
  return Object.fromEntries(all.map((name) => [name, flags[name]]))
}

function withProvider(values: Options): Options {
  const { provider, ...rest } = values
  if (provider === undefined) return values
  if (rest.agent !== undefined) throw new UsageError('give --provider only once')
  return { ...rest, agent: provider }
}


export type ForwardedName = (typeof forwardedRequests)[number]
export type ForwardedRequests = Pick<DaemonClient, ForwardedName>
type Transport = (name: ForwardedName, ...args: unknown[]) => Promise<unknown>

export function isForwardedRequest(name: unknown): name is ForwardedName {
  return typeof name === 'string' && forwardedRequests.some((allowed) => allowed === name)
}

export function forwardDaemonRequest(
  client: DaemonClient,
  name: unknown,
  args: unknown[],
): Promise<unknown> {
  if (!isForwardedRequest(name)) throw new Error('unknown daemon request')
  if (name === 'uploadAttachment' && !(args[1] instanceof Uint8Array)) {
    throw new Error('attachment bytes must be a Uint8Array')
  }
  const method = client[name] as (...args: unknown[]) => Promise<unknown>
  return method.apply(client, args)
}

export function daemonRequests(request: Transport): ForwardedRequests {
  return Object.fromEntries(
    forwardedRequests.map((name) => [name, (...args: unknown[]) => request(name, ...args)]),
  ) as ForwardedRequests
}

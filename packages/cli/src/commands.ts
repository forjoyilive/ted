export type HandlerName = (typeof commands)[number]['handler']
export interface Invocation {
  handler: HandlerName
  args: string[]
  options: Options
}

export function helpText(table: readonly CommandDefinition[] = commands): string {
  return [
    'Usage:',
    ...table.map((entry) => entry.help).filter(Boolean),
    '',
    'Inside a Run, commands act on the Run’s own Task (TED_TASK).',
  ].join('\n')
}

export function parseInvocation(
  argv: string[],
  env: NodeJS.ProcessEnv,
  table: readonly CommandDefinition<HandlerName>[] = commands,
): Invocation {
  try {
    const vocabulary = Object.assign(
      {},
      ...table.map((entry) => entry.options),
    ) as ParseArgsOptionsConfig
    const parsed = parseArgs({
      args: argv,
      allowPositionals: true,
      strict: true,
      options: vocabulary,
    })
    const values = parsed.values as Options
    const names = table.filter((entry) =>
      entry.name.split(' ').every((word, index) => parsed.positionals[index] === word),
    )
    const depth = Math.max(0, ...names.map((entry) => entry.name.split(' ').length))
    const named = names.filter((entry) => entry.name.split(' ').length === depth)
    const args = parsed.positionals.slice(depth)
    const hasTask = values.task !== undefined || !!tedEnv('TED_TASK', env)
    const scope: Scope = hasTask
      ? 'task'
      : named.some((entry) => entry.name === 'comment') && tedEnv('TED_AUTOMATION', env)
        ? 'automation'
        : named.some((entry) => entry.name === 'ask' || entry.name === 'task propose') &&
            tedEnv('TED_PLAN', env)
          ? 'plan'
          : 'task'
    const selected = named.filter(
      (entry) =>
        (entry.scope === undefined || entry.scope === scope) &&
        (entry.argumentOrOption === undefined ||
          args.length > 0 ||
          values[entry.argumentOrOption] !== undefined) &&
        args.length >= entry.min &&
        (entry.max === null || args.length <= entry.max) &&
        (entry.requires ?? []).every((key) => values[key] !== undefined && values[key] !== false) &&
        (entry.excludes ?? []).every((key) => values[key] === undefined),
    )
    const [entry] = selected
    if (selected.length !== 1 || entry === undefined) throw new UsageError('')
    parseArgs({ args: argv, allowPositionals: true, strict: true, options: entry.options })
    return { handler: entry.handler, args, options: values }
  } catch (error) {
    if (error instanceof UsageError) throw error
    throw new UsageError(error instanceof Error ? error.message : String(error))
  }
}
